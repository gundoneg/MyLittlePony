"""Builds qwen_mercury_port.ipynb — port Qwen3.5-9B to a Mercury-2-style diffusion LM by the
weight-translator C (the method proven on supra50m in c_mercury_port runs 1-7).

9B-scale engineering (Kaggle 2x T4, 32GB total):
  * transformers-based (Qwen3.5 has its own quirks: QK-norm, possibly untied head) with a
    custom layer loop for truncated sub-stacks, bidirectional 4D masks, [MASK]-embedding
    injection via inputs_embeds;
  * fp16 weights sharded across both GPUs (device_map='balanced'); C stays fp32 (~1M params);
  * per-block deltas applied via forward HOOKS (y += ((x@V) A(z)^T) U^T) -- the 9B weights are
    never materialized/modified; U,V from torch.svd_lowrank (cached);
  * KD = top-k teacher targets (vocab 152K full-softmax KD does not fit);
  * WARM arm omitted at 9B (Adam states for 9B = ~72GB, impossible on T4s; the warm metric is
    established on the supra port);
  * PILOT mode: the same code first validated on Qwen3.5-0.8B (~15 min) -- no local smoke is
    possible (no transformers in the dev container), so the pilot IS the smoke.

Run locally: python build_qwen_mercury_nb.py   (generates + syntax-checks the notebook)
"""
