def make_bias(B, T, causal):
    m = (torch.full((T, T), torch.finfo(torch.float32).min).triu(1)
         if causal else torch.zeros(T, T))
    return m[None, None].expand(B, 1, T, T)


def run_stack(ids, Lt, causal=False, mask_row=None):
    B, T = ids.shape
    h = core.embed_tokens(ids.clamp_max(V - 1))
    if mask_row is not None:
        h = torch.where((ids == MASK_ID)[..., None], mask_row, h)
    pos_ids = torch.arange(T)[None].expand(B, T)
    pe = core.rotary_emb(h, pos_ids) if hasattr(core, "rotary_emb") else None
    bias = make_bias(B, T, causal)
    for l in range(Lt):
        kw = dict(attention_mask=bias, position_ids=pos_ids)
        if pe is not None:
            kw["position_embeddings"] = pe
        try:
            out = layers[l](h, **kw)
        except TypeError:
            kw.pop("position_embeddings", None)
            out = layers[l](h, **kw)
        h = out[0] if isinstance(out, tuple) else out
    return model.lm_head(core.norm(h))


