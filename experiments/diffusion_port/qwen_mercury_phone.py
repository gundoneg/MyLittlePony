# ---------------- diffusion core ----------------
def sample_mask_rate(b):
    return ARGS.eps_t + (1.0 - ARGS.eps_t) * torch.rand(b)


def forward_mask(x0, t):
    B, L = x0.shape
    noise = torch.rand(B, L)
    m = noise < t[:, None].expand(B, L)
    empty = ~m.any(dim=1)
    if empty.any():
        m[empty.nonzero(as_tuple=True)[0], noise[empty].argmin(dim=1)] = True
    return torch.where(m, torch.full_like(x0, MASK_ID), x0), m


def masked_diffusion_loss(logits, x0, m, t, kd_probs=None, kd_idx=None):
    B, T = x0.shape
    lm = logits[m].float()
    ce = F.cross_entropy(lm, x0[m], reduction="none")
    if kd_probs is not None:
        q = lm.log_softmax(-1)
        ce = (1 - ARGS.kd) * ce - ARGS.kd * (kd_probs * q.gather(1, kd_idx)).sum(1)
    seq_idx = torch.arange(B)[:, None].expand(B, T)[m]
    return (torch.zeros(B).index_add_(0, seq_idx, ce) / (t * T)).mean()


@torch.no_grad()
def masked_ce_at(fn, ids, t_val, n=8):
    x0 = ids[:n]
    x_t, m = forward_mask(x0, torch.full((x0.shape[0],), t_val))
    return F.cross_entropy(fn(x_t)[m].float(), x0[m]).item()


@torch.no_grad()
def denoise_v2(fn, ids, frozen, steps=32, temp0=1.0, alg_temp=0.3, remask_frac=0.15,
               prior=None, beta=0.6, samp_beta=0.4, rep_gamma=0.8, ban_ids=None,
               temp_floor=0.7, no_repeat=3):
    B, L = ids.shape
    n0 = int(((ids == MASK_ID) & ~frozen).sum().item())
    if n0 == 0:
        return ids
    lp = None if prior is None else torch.log(prior.clamp_min(1e-8))
    for s in range(steps):
        masked = (ids == MASK_ID) & ~frozen
        n_left = int(masked.sum().item())
        if n_left == 0:
            break
        logits = fn(ids).float()
        if ban_ids is not None:
            for b in ban_ids:
                logits[..., b] = float("-inf")
        if lp is not None and samp_beta > 0:
            logits = logits - samp_beta * lp
        if rep_gamma > 0:
            for b in range(B):
                seen = ids[b][ids[b] != MASK_ID]
                if seen.numel():
                    logits[b] = logits[b] - rep_gamma * torch.log1p(
                        torch.bincount(seen, minlength=V).float())
        if no_repeat > 0:
            for b in range(B):
                row = ids[b].tolist(); seen = {}
                for j in range(L - no_repeat + 1):
                    sg = row[j:j + no_repeat]
                    if MASK_ID in sg:
                        continue
                    seen.setdefault(tuple(sg[:-1]), set()).add(sg[-1])
                for i in range(no_repeat - 1, L):
                    ctx = tuple(row[i - (no_repeat - 1):i])
                    if MASK_ID in ctx:
                        continue
                    for tk in seen.get(ctx, ()):
                        logits[b, i, tk] = float("-inf")
        tau = temp0 * max(0.0, 1.0 - s / max(1, steps - 1))
        if s < int(0.9 * steps):
            tau = max(tau, temp_floor)
        if tau > 0.05:
            probs = (logits / tau).softmax(-1)
            pred = torch.multinomial(probs.view(-1, V), 1).view(B, L)
        else:
            probs = logits.softmax(-1)
            pred = probs.argmax(-1)
        conf = probs.gather(-1, pred[..., None]).squeeze(-1).clamp_min(1e-9).log()
        if lp is not None:
            conf = conf - beta * lp[pred]
        conf = conf.masked_fill(~masked, float("-inf"))
        if alg_temp > 0:
            g = torch.rand_like(conf).clamp_min(1e-9)
            conf = conf + alg_temp * (-(-g.log()).log()) * (s < steps // 2)
        k = max(1, min(n_left, n_left - int(n0 * math.cos(math.pi / 2 * (s + 1) / steps))))
        idxs = conf.view(-1).topk(k).indices
        ids.view(-1)[idxs] = pred.view(-1)[idxs]
        if remask_frac > 0 and s < steps // 2:
            rev = (ids != MASK_ID) & ~frozen
            if rev.any():
                cur = probs.gather(-1, ids.clamp_max(V - 1)[..., None]).squeeze(-1)
                cur = cur.masked_fill(~rev, float("inf"))
                q = max(1, int(rev.sum().item() * remask_frac))
                ids.view(-1)[(-cur.view(-1)).topk(q).indices] = MASK_ID
    masked = (ids == MASK_ID) & ~frozen
    if masked.any():
        ids = torch.where(masked, fn(ids).float().argmax(-1), ids)
    return ids


@torch.no_grad()
def semi_ar_generate(fn, prompt, total_len, block=16, steps_per_block=16, **kw):
    ids = prompt.clone()
    while ids.shape[1] < total_len:
        b = min(block, total_len - ids.shape[1])
        win = torch.cat([ids, torch.full((ids.shape[0], b), MASK_ID, dtype=torch.long)], 1)
        fr = torch.zeros_like(win, dtype=torch.bool)
        fr[:, :ids.shape[1]] = True
        ids = denoise_v2(fn, win, fr, steps=steps_per_block, **kw)
    return ids


