"""Phase 9 — depth-entanglement / layer-redundancy probe for a REAL model (supra50m,
a 12-layer Llama), to answer: are real LLM layers closer to our toy's WORST CASE
(every layer unique & order-bound -> must train the translator C at the target depth)
or to the TIED/redundant regime (layers interchangeable -> a shallow zoo could cover the
type repertoire and depth-extrapolation would work)?

Metrics (no transformers dep; on-distribution inputs are self-generated by the model):
  * update     -- ||x_{l+1}-x_l|| / ||x_l||: how much layer l changes the residual stream
                  (small => 'refinement'/redundant).
  * cos        -- cos(x_l, x_{l+1}): high => the layer barely moves the representation.
  * drop-KL    -- KL(full || skip layer l): how much layer l matters to the output.
  * swap-KL    -- KL(full || swap layers l,l+1): order-sensitivity = NON-interchangeability.
  * wsim       -- gauge-invariant cross-layer weight-spectrum similarity (mean off-diagonal).

Anchor (our phase-8 toy, worst case): every layer matters (L=3 ablation 54/31/77) and the
pointer-chase is strictly ordered -> high drop-KL & high swap-KL, low cross-layer sim.
"""
import torch
import torch.nn.functional as F
from llama_min import MinLlama, load_vocab, decode


def kl(p_logits, q_logits):
    """mean_token KL(softmax(p) || softmax(q))."""
    lp = p_logits.log_softmax(-1)
    lq = q_logits.log_softmax(-1)
    return (lp.exp() * (lp - lq)).sum(-1).mean().item()


@torch.no_grad()
def activation_metrics(m, idx):
    full, hs = m.forward(idx, capture=True)
    upd, cos, dropkl, swapkl = [], [], [], []
    for l in range(m.L):
        a, b = hs[l], hs[l + 1]
        upd.append(((b - a).norm(dim=-1) / (a.norm(dim=-1) + 1e-6)).mean().item())
        cos.append(F.cosine_similarity(a, b, dim=-1).mean().item())
        dropkl.append(kl(full, m.forward(idx, skip=l)))
        if l < m.L - 1:
            swapkl.append(kl(full, m.forward(idx, swap=(l, l + 1))))
    return upd, cos, dropkl, swapkl


def layer_signature(m, l):
    """Gauge-invariant per-layer descriptor: concatenated normalized singular-value
    spectra of the layer's projections (spectrum is invariant to input/output basis)."""
    parts = []
    for n in ("self_attn.q_proj", "self_attn.k_proj", "self_attn.v_proj", "self_attn.o_proj",
              "mlp.gate_proj", "mlp.up_proj", "mlp.down_proj"):
        s = torch.linalg.svdvals(m.w[f"model.layers.{l}.{n}.weight"])
        parts.append(s / (s.norm() + 1e-9))
    return torch.cat(parts)


def weight_similarity(m):
    sigs = torch.stack([layer_signature(m, l) for l in range(m.L)])
    sigs = sigs / sigs.norm(dim=1, keepdim=True)
    S = sigs @ sigs.t()
    off = S[~torch.eye(m.L, dtype=bool)]
    return S, off.mean().item()


def bar(v, lo, hi, w=20):
    f = max(0.0, min(1.0, (v - lo) / (hi - lo + 1e-9)))
    return "#" * int(f * w) + "." * (w - int(f * w))


if __name__ == "__main__":
    m = MinLlama()
    inv = load_vocab()
    # on-distribution probe: self-generate a few sequences from BOS
    torch.manual_seed(0)
    seqs = [m.generate(torch.tensor([[1]]), 160, temperature=0.9)[:, 1:] for _ in range(3)]
    idx = torch.cat(seqs, 0)                                  # (3, ~160)
    print(f"supra50m  L={m.L}  d={m.d}  (real 50M Llama)\n")

    upd, cos, dropkl, swapkl = activation_metrics(m, idx)
    S, wmean = weight_similarity(m)

    print(f"{'layer':>5} | {'update':>7} | {'cos(l,l+1)':>10} | {'drop-KL':>8} | {'swap-KL(l,l+1)':>14}")
    print("-" * 60)
    for l in range(m.L):
        sk = f"{swapkl[l]:.2f} {bar(swapkl[l],0,3,10)}" if l < m.L - 1 else ""
        print(f"{l:>5} | {upd[l]:>7.2f} | {cos[l]:>10.2f} | {dropkl[l]:>5.2f} {bar(dropkl[l],0,5,6)} | {sk:>14}")

    import statistics as st
    print(f"\nsummary:")
    print(f"  mean drop-KL        {st.mean(dropkl):.2f}  (low => many layers prunable/redundant)")
    print(f"  median drop-KL      {st.median(dropkl):.2f}")
    print(f"  frac layers drop-KL<0.5  {sum(d<0.5 for d in dropkl)/m.L:.0%}  (interchangeable-ish)")
    print(f"  mean swap-KL        {st.mean(swapkl):.2f}  (low => order-insensitive => interchangeable)")
    print(f"  mean update ratio   {st.mean(upd):.2f}")
    print(f"  cross-layer weight-spectrum sim (mean off-diag)  {wmean:.2f}  (high => similar layer 'types')")
